def get_wait_message(media_type: str = "text") -> str:
    """
    Возвращает случайную фразу ожидания в зависимости от типа задачи.
    media_type: 'text', 'image', 'video', 'audio'
    """
    if media_type == "image":
        return f"⏳ <i>{random.choice(WAIT_IMAGE)}</i>"
    elif media_type == "video":
        return f"⏳ <i>{random.choice(WAIT_VIDEO)}</i>"
    elif media_type == "audio":
        return f"⏳ <i>{random.choice(WAIT_AUDIO)}</i>"
    else:
        return f"⏳ <i>{random.choice(WAIT_TEXT)}</i>"
