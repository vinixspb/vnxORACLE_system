def get_wait_message(media_type: str = "text") -> str:
    """Возвращает случайную фразу ожидания в зависимости от типа задачи."""
    if media_type == "image":
        return f"⏳ <i>{random.choice(WAIT_IMAGE)}</i>"
    elif media_type == "video":
        return f"⏳ <i>{random.choice(WAIT_VIDEO)}</i>"
    elif media_type == "audio":
        return f"⏳ <i>{random.choice(WAIT_AUDIO)}</i>"
    else:
        return f"⏳ <i>{random.choice(WAIT_TEXT)}</i>"

class DynamicWaitMessage:
    """
    Асинхронный фоновый воркер. 
    Каждые 4 секунды обновляет сообщение Telegram новой шуткой.
    """
    def __init__(self, message: Message, media_type: str = "text", prefix: str = ""):
        self.message = message
        self.media_type = media_type
        self.prefix = prefix
        self._task = None
        self.chat_id = message.chat_id
        self.message_id = message.message_id
        self.last_text = ""

    async def _update_loop(self):
        bot = self.message.get_bot()
        try:
            while True:
                await asyncio.sleep(4)  # 🔥 Меняем шутку ровно каждые 4 секунды
                
                new_text = f"{self.prefix}{get_wait_message(self.media_type)}"
                # 🔥 Жесткая защита от повторов: крутим рулетку, пока не выпадет новая шутка
                while new_text == self.last_text:
                    new_text = f"{self.prefix}{get_wait_message(self.media_type)}"
                
                self.last_text = new_text
                
                try:
                    await bot.edit_message_text(
                        chat_id=self.chat_id,
                        message_id=self.message_id,
                        text=new_text,
                        parse_mode='HTML'
                    )
                except Exception as e:
                    if "Message is not modified" not in str(e):
                        logger.warning(f"WaitMsg Edit Error: {e}")
        except asyncio.CancelledError:
            pass # Нормальное завершение задачи

    def start(self):
        if self.message:
            self._task = asyncio.create_task(self._update_loop())

    def stop(self):
        if self._task and not self._task.done():
            self._task.cancel()
